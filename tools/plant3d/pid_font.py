def width(text, h):
    """The length of a text at height h, in the same units as h (the last letter's spacing left out)."""
    n = len(text)
    return 0.0 if n == 0 else (n * ADVANCE - 1.0) * h / CAP


def check(text):
    """The characters of a text the lettering has no glyph for (empty when it can be drawn)."""
    return sorted({c for c in text if c not in GLYPHS})


def table():
    """The strokes for drawings/index.json: {character: [[x, y, x, y, …] per stroke]}, sorted, numbers rounded."""
    out = {}
    for c in sorted(GLYPHS):
        out[c] = [[round(v, 2) for p in s for v in p] for s in GLYPHS[c]]
    return out
